int DTerminalUtil::displayWidth(const QString &text)
{
    const QVector<uint> codePoints = text.toUcs4();
    int width = 0;
    for (uint codePoint : codePoints)
        width += DCharWidth::cellWidth(codePoint);
    return width;
}

DTerminalCellColor::DTerminalCellColor(quint8 colorSpace, int value)
    : space(colorSpace)
{
    switch (colorSpace) {
    case ColorSpaceDefault:
        primary = value & 1;
        break;
    case ColorSpaceSystem:
        primary = value & 7;
        secondary = (value >> 3) & 1;
        break;
    case ColorSpaceIndex256:
        primary = value & 255;
        break;
    case ColorSpaceRgb:
        primary = value >> 16;
        secondary = value >> 8;
        tertiary = value;
        break;
    default:
        space = ColorSpaceUndefined;
        break;
    }
}

