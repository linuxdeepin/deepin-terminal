int DCharWidth::cellWidth(uint codePoint)
{
    if (s_gb18030Mode)
        return widthByGB18030Table(codePoint);
    return widthByUnicodeData(codePoint);
}

int DCharWidth::widthByUnicodeData(uint codePoint)
{
    // C0/C1 控制区与代理区不占单元格
    if (codePoint < 0x20 || (codePoint >= 0x7f && codePoint < 0xa0))
        return -1;
    if (codePoint >= 0xd800 && codePoint <= 0xdfff)
        return -1;

    // 先判宽字符（与历史实现判定顺序一致），再判组合字符
    const int eastAsianWidth = u_getIntPropertyValue(static_cast<UChar32>(codePoint), UCHAR_EAST_ASIAN_WIDTH);
    if (eastAsianWidth == U_EA_WIDE || eastAsianWidth == U_EA_FULLWIDTH)
        return 2;
    if (u_getIntPropertyValue(static_cast<UChar32>(codePoint), UCHAR_CANONICAL_COMBINING_CLASS) != 0)
        return 0;
    return 1;
}

int DCharWidth::widthByGB18030Table(uint codePoint)
{
    if (codePoint < 256)
        return kGB18030DirectWidth[codePoint];
    if (codePoint >= 0xd800 && codePoint <= 0xdfff)
        return -1;

    // 二分查找宽度为 2 的区间
    int low = 0;
    int high = static_cast<int>(sizeof(kGB18030WideRanges) / sizeof(kGB18030WideRanges[0])) - 1;
    while (low <= high) {
        const int mid = (low + high) / 2;
        if (kGB18030WideRanges[mid].last < codePoint) {
            low = mid + 1;
        } else if (kGB18030WideRanges[mid].first > codePoint) {
            high = mid - 1;
        } else {
            return 2;
        }
    }

    if (u_getIntPropertyValue(static_cast<UChar32>(codePoint), UCHAR_CANONICAL_COMBINING_CLASS) != 0)
        return 0;
    return 1;
}

void DCharWidth::setGB18030Mode(bool enable)
{
    s_gb18030Mode = enable;
}

bool DCharWidth::gb18030Mode()
{
    return s_gb18030Mode;
}
